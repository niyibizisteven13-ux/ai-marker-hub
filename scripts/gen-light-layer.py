#!/usr/bin/env python3
# Run from the repository root: python3 scripts/gen-light-layer.py
# Generates the light-mode layer: the dark app's generic utility classes mapped to light equivalents.
def esc(c): return c.replace(':','\\:').replace('/','\\/').replace('[','\\[').replace(']','\\]').replace('.','\\.')
S = 'html.theme-light .app-shell'
NOT = ':not(:where(.keep-colors, .keep-colors *))'
lines = []
def rule(cls, decl, state=''):
    lines.append(f'{S} .{esc(cls)}{NOT}{state} {{ {decl} }}')
# Translucent white fills/borders become translucent dark ones.
alphas = {'5':.05,'10':.10,'15':.15,'20':.2,'25':.25,'30':.3,'[0.02]':.02,'[0.025]':.025,'[0.03]':.03,'[.035]':.035,'[0.04]':.04,'[0.05]':.05,'[0.06]':.06,'[0.07]':.07,'[.07]':.07,'[0.08]':.08,'[.08]':.08,'[0.09]':.09,'[0.1]':.1,'[0.12]':.12,'[0.14]':.14,'[0.16]':.16,'[0.18]':.18}
for a, v in alphas.items():
    bg = f'background-color: rgb(20 18 14 / {round(v*0.9,3)});'
    bd = f'border-color: rgb(20 18 14 / {round(min(1, v*1.15+0.02),3)});'
    rule(f'bg-white/{a}', bg); rule(f'hover:bg-white/{a}', bg, ':hover'); rule(f'group-hover:bg-white/{a}', bg.replace(';',''), '') if False else None
    rule(f'border-white/{a}', bd); rule(f'hover:border-white/{a}', bd, ':hover')
    rule(f'ring-white/{a}', f'--tw-ring-color: rgb(20 18 14 / {round(v*1.2,3)});'); rule(f'divide-white/{a}', bd.replace('border-color','border-color'))
# Text greys: the dark scale read backwards.
TXT = {'white':'var(--app-text)','neutral-100':'#1f1e1d','neutral-200':'#2a2926','neutral-300':'#3b3935','neutral-400':'#5a5853','neutral-500':'#73706a','neutral-600':'#8a8780',
       'stone-100':'#1f1e1d','stone-200':'#2a2926','stone-300':'#3b3935','stone-400':'#5a5853','stone-500':'#73706a','stone-600':'#8a8780','white/80':'rgb(31 30 29 / .8)','white/50':'rgb(31 30 29 / .55)'}
COLORED = ''.join(f':not([class*="{c}"])' for c in ['bg-[var(--brand','bg-rose','bg-red','bg-emerald','bg-green','bg-sky','bg-blue','bg-indigo','bg-violet','bg-fuchsia','bg-orange','bg-amber','bg-teal','bg-black','bg-neutral-9','bg-neutral-8','bg-stone-9','bg-stone-8','bg-gradient','bg-[#'])
for k, v in TXT.items():
    sel = f'{S} .{esc("text-"+k)}{NOT}{COLORED}'
    lines.append(f'{sel} {{ color: {v}; }}')
    lines.append(f'{S} .{esc("hover:text-"+k)}{NOT}{COLORED}:hover {{ color: {v}; }}')
    lines.append(f'{S} .group:hover .{esc("group-hover:text-"+k)}{NOT}{COLORED} {{ color: {v}; }}')
    lines.append(f'{S} .{esc("placeholder:text-"+k)}{NOT}::placeholder {{ color: {v}; }}')
# Dark solid panels used by older parts (stone).
for k, v in {'stone-950/60':'rgb(244 243 239 / .8)','stone-900/70':'#ffffff','stone-900':'#ffffff','stone-800':'#efede7','neutral-900':'#f4f3ef','neutral-800':'#ebe9e3'}.items():
    rule(f'bg-{k}', f'background-color: {v};')
for k in ['stone-700','stone-800']:
    rule(f'hover:bg-{k}', 'background-color: #e6e3dc;', ':hover'); rule(f'border-{k}', 'border-color: rgb(20 18 14 / .12);'); rule(f'hover:border-{k}', 'border-color: rgb(20 18 14 / .2);', ':hover'); rule(f'ring-{k}', '--tw-ring-color: rgb(20 18 14 / .14);')
# Solid white buttons (the "inverted" primary) become dark ones in light mode, with their dark text turned light.
lines.append(f'{S} .bg-white{NOT}:is(button, a, [role=button]) {{ background-color: #1f1e1d; color: #fff; }}')
lines.append(f'{S} :is(button, a, [role=button]).bg-white{NOT} :is(.text-neutral-900, .text-stone-900, .text-black) {{ color: #fff; }}')
lines.append(f'{S} .bg-white{NOT}:is(button, a, [role=button]):is(.text-neutral-900, .text-stone-900, .text-black) {{ color: #fff; }}')
lines.append(f'{S} .{esc("hover:bg-white")}{NOT}:is(button, a, [role=button]):hover {{ background-color: #000; }}')
open('src/theme/light-layer.css','w').write('/* Generated by scripts/gen-light-layer.py: the dark app\'s utility classes mapped for the light theme. Elements inside .keep-colors (file previews, documents, videos) keep their own colours. */\n' + '\n'.join(l for l in lines if l) + '\n')
print(len(lines))
