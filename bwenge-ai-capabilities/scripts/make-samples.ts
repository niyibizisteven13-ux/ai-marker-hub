import { writeFile } from 'node:fs/promises';
import { renderDiagram } from '../src/ai/drawing/diagram.js';
import { renderVegaLite } from '../src/ai/drawing/chart.js';
import { sanitizeSvg } from '../src/ai/drawing/svgSanitizer.js';
import { svgToPng } from '../src/ai/drawing/rasterize.js';
import { generatePdf } from '../src/ai/files/generators/pdf.js';
import { generateDocx } from '../src/ai/files/generators/docx.js';
import { generatePptx } from '../src/ai/files/generators/pptx.js';
import { generateXlsx } from '../src/ai/files/generators/xlsx.js';

const diagram = sanitizeSvg(renderDiagram({
  title: 'How Bwenge marks an exam', direction: 'TB',
  nodes: [
    { id: 'a', label: 'Teacher uploads scripts and rubric', color: 'orange', shape: 'rounded' },
    { id: 'b', label: 'AI reads each answer and marks it against the rubric', color: 'teal' },
    { id: 'c', label: 'Low confidence?', shape: 'diamond', color: 'gold' },
    { id: 'd', label: 'Teacher reviews and adjusts', color: 'navy' },
    { id: 'e', label: 'Results and reports', shape: 'ellipse', color: 'green' },
  ],
  edges: [{ from: 'a', to: 'b' }, { from: 'b', to: 'c' }, { from: 'c', to: 'd', label: 'yes' }, { from: 'c', to: 'e', label: 'no' }, { from: 'd', to: 'e' }],
}));
await writeFile('samples/diagram.svg', diagram);
await writeFile('samples/diagram.png', svgToPng(diagram, { width: 1200 }).data);

const chart = sanitizeSvg(await renderVegaLite({
  title: 'Average score by class', data: { values: [{ cls: '6A', term: 'Term 1', s: 68 }, { cls: '6A', term: 'Term 2', s: 74 }, { cls: '6B', term: 'Term 1', s: 61 }, { cls: '6B', term: 'Term 2', s: 70 }, { cls: '6C', term: 'Term 1', s: 77 }, { cls: '6C', term: 'Term 2', s: 82 }] },
  mark: 'bar', encoding: { x: { field: 'cls', type: 'nominal', title: 'Class' }, xOffset: { field: 'term' }, y: { field: 's', type: 'quantitative', title: 'Average score (%)' }, color: { field: 'term', type: 'nominal', title: 'Term' } },
}), { maxBytes: 3_000_000 });
await writeFile('samples/chart.svg', chart);
const chartPng = svgToPng(chart, { width: 1200 });
await writeFile('samples/chart.png', chartPng.data);

const drawing = sanitizeSvg(`<svg viewBox="0 0 640 400"><rect width="640" height="400" fill="#F4F7FA"/><circle cx="520" cy="90" r="46" fill="#F6B94A"/><path d="M0 320 Q160 220 320 300 T640 280 V400 H0Z" fill="#2E8B57"/><path d="M0 350 Q200 290 400 345 T640 330 V400 H0Z" fill="#1F6B43"/><rect x="250" y="190" width="120" height="100" fill="#D2691E"/><polygon points="240,190 310,130 380,190" fill="#8B3A0E"/><rect x="295" y="230" width="30" height="60" fill="#F4EFE3"/><text x="320" y="60" text-anchor="middle" font-size="26" font-weight="700" fill="#12305A">Farm near Musanze</text></svg>`);
await writeFile('samples/drawing.svg', drawing);
await writeFile('samples/drawing.png', svgToPng(drawing, { width: 1000 }).data);

const resolver = async (r: any) => (r.fileId === 'chart' ? { data: chartPng.data, type: 'png' as const, width: chartPng.width, height: chartPng.height } : null);
const spec = {
  title: 'Term 2 Marking Report', subtitle: 'Class 6A to 6C \u2014 Mathematics', author: 'Bwenge', language: 'en', footer: 'Generated by Bwenge', blocks: [
    { type: 'heading' as const, level: 1, text: 'Summary' },
    { type: 'paragraph' as const, text: 'All three classes improved from Term 1 to Term 2. **Class 6C** had the highest average (82%), and *Class 6B* improved the most (+9 points). Muraho neza! Merci aux enseignants.' },
    { type: 'image' as const, fileId: 'chart', caption: 'Average score by class and term' },
    { type: 'heading' as const, level: 2, text: 'Results' },
    { type: 'table' as const, header: ['Class', 'Term 1', 'Term 2', 'Change'], rows: [['6A', '68', '74', '+6'], ['6B', '61', '70', '+9'], ['6C', '77', '82', '+5']] },
    { type: 'heading' as const, level: 2, text: 'Next steps' },
    { type: 'list' as const, ordered: true, items: ['Review fractions with **6B**', 'Share Class 6C worksheets', 'Re-test in Term 3'] },
    { type: 'quote' as const, text: 'Small steps, every day.' },
  ],
};
await writeFile('samples/report.pdf', await generatePdf(spec, resolver));
await writeFile('samples/report.docx', await generateDocx(spec, resolver));
await writeFile('samples/deck.pptx', await generatePptx({ title: 'Bwenge for Schools', subtitle: 'Marking, results, and insight', slides: [
  { layout: 'bullets', title: 'Why teachers like it', bullets: ['Marks against your rubric', 'Teacher stays in control', 'Results in minutes'] },
  { layout: 'image', title: 'Class averages', image: { fileId: 'chart', caption: 'Term 1 vs Term 2' } },
  { layout: 'quote', quote: 'It gave me my weekends back.', attribution: 'A teacher' },
] }, resolver));
await writeFile('samples/marks.xlsx', await generateXlsx({ sheets: [{ name: 'Class 6A', columns: [{ header: 'Student' }, { header: 'Test 1', type: 'number' }, { header: 'Test 2', type: 'number' }, { header: 'Average', type: 'number' }], rows: [['Amina', 17, 19, '=AVERAGE(B2:C2)'], ['Eric', 14, 15, '=AVERAGE(B3:C3)'], ['Class average', '=AVERAGE(B2:B3)', '=AVERAGE(C2:C3)', '=AVERAGE(D2:D3)']], autoFilter: true }] }));
